// Build-time tool: compiles a GLSL shader to SPIR-V and writes it as a C++ header, so the runtime's own
// shaders ship precompiled.  spirv_embed <stage: comp|vert|frag> <in.glsl> <out.h> <array name>
#include <shaderc/shaderc.h>

#include <cstdio>
#include <cstring>
#include <fstream>
#include <sstream>
#include <string>

int main(int argc, char** argv) {
    if (argc != 5) {
        std::fprintf(stderr, "usage: spirv_embed comp|vert|frag IN OUT NAME\n");
        return 2;
    }
    const shaderc_shader_kind kind = std::strcmp(argv[1], "vert") == 0   ? shaderc_vertex_shader
                                     : std::strcmp(argv[1], "frag") == 0 ? shaderc_fragment_shader
                                                                         : shaderc_compute_shader;
    std::ifstream in(argv[2], std::ios::binary);
    if (!in) {
        std::fprintf(stderr, "spirv_embed: cannot read %s\n", argv[2]);
        return 1;
    }
    std::stringstream text;
    text << in.rdbuf();
    const std::string source = text.str();

    shaderc_compiler_t compiler = shaderc_compiler_initialize();
    shaderc_compile_options_t options = shaderc_compile_options_initialize();
    shaderc_compile_options_set_target_env(options, shaderc_target_env_vulkan, shaderc_env_version_vulkan_1_3);
    shaderc_compile_options_set_optimization_level(options, shaderc_optimization_level_performance);
    shaderc_compilation_result_t result =
        shaderc_compile_into_spv(compiler, source.data(), source.size(), kind, argv[2], "main", options);
    if (shaderc_result_get_compilation_status(result) != shaderc_compilation_status_success) {
        std::fprintf(stderr, "%s", shaderc_result_get_error_message(result));
        return 1;
    }
    const auto* words = reinterpret_cast<const uint32_t*>(shaderc_result_get_bytes(result));
    const size_t count = shaderc_result_get_length(result) / 4;

    std::ofstream out(argv[3], std::ios::binary);
    out << "// Generated by spirv_embed from " << argv[2] << ": do not edit.\n#pragma once\n#include <cstdint>\n"
        << "alignas(4) inline constexpr uint32_t " << argv[4] << "[] = {";
    for (size_t i = 0; i < count; ++i) {
        char word[32];
        std::snprintf(word, sizeof word, "%s0x%08X,", i % 8 == 0 ? "\n    " : " ", words[i]);
        out << word;
    }
    out << "\n};\n";
    shaderc_result_release(result);
    shaderc_compile_options_release(options);
    shaderc_compiler_release(compiler);
    return out ? 0 : 1;
}
